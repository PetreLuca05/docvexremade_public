// Paragraphs (split at blank lines), and lines starting with "- " as a list.
function Paragraphs({ text }) {
  return text.split(/\n{2,}/).map((block, j) => {
    const lines = block.split('\n');
    const items = lines.filter((l) => /^\s*[-•]\s+/.test(l));
    if (!items.length) return <p key={j}>{block}</p>;
    const lead = lines.filter((l) => !/^\s*[-•]\s+/.test(l)).join(' ');
    return (
      <div key={j}>
        {lead && <p>{lead}</p>}
        <ul>
          {items.map((l, k) => (
            <li key={k}>{l.replace(/^\s*[-•]\s+/, '')}</li>
          ))}
        </ul>
      </div>
    );
  });
}

const REDUCED =
  typeof window !== 'undefined' && window.matchMedia('(prefers-reduced-motion: reduce)').matches;

// The answer typed out a few characters at a time (`animate`: the newest
// one); screen readers get it whole at once. `onType` keeps the chat
// scrolled to it while it grows.
function Answer({ text, animate, onType }) {
  const [shown, setShown] = useState(animate && !REDUCED ? 0 : text.length);
  useEffect(() => {
    if (shown >= text.length) return;
    const id = setTimeout(() => {
      setShown((n) => Math.min(text.length, n + 3));
      onType?.();
    }, 18);
    return () => clearTimeout(id);
  }, [shown, text, onType]);
  const typing = shown < text.length;
  return (
    <>
      <span className="visually-hidden">{text}</span>
      <div aria-hidden="true" className={typing ? 'is-typing-text' : undefined}>
        <Paragraphs text={text.slice(0, shown)} />
      </div>
    </>
  );
}

// Before the first question: a single field with a send button. From the
// first question on: a chat box, the conversation scrolling above the field.
export default function AskDocvex() {
  const { lang } = useLang();
  const t = T[lang];
  const [question, setQuestion] = useState('');
  const [turns, setTurns] = useState([]);
  const [pending, setPending] = useState('');
  const [remaining, setRemaining] = useState(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');
  const input = useRef(null);
  const log = useRef(null);
  const out = remaining === 0;
  const chat = turns.length > 0 || Boolean(pending);

  // Keep the newest message in view (also while an answer types out).
  const toBottom = useCallback(() => {
    const el = log.current;
    if (el) el.scrollTop = el.scrollHeight;
  }, []);
  useEffect(toBottom, [turns, pending, error, toBottom]);

  async function ask(event) {
    event.preventDefault();
    const q = question.trim();
    if (!q || busy || out) return;
    if (q.length > 500) {
      setError(t.tooLong);
      return;
    }
    if (!ENDPOINT) {
      setError(t.unavailable);
      return;
    }
    setBusy(true);
    setError('');
    setPending(q);
    setQuestion('');
    try {
      const res = await fetch(ENDPOINT, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          apikey: import.meta.env.VITE_SUPABASE_ANON_KEY,
          Authorization: `Bearer ${import.meta.env.VITE_SUPABASE_ANON_KEY}`,
        },
        body: JSON.stringify({
          question: q,
          history: turns.map(({ q: tq, a }) => ({ q: tq, a })),
        }),
      });
      const data = await res.json().catch(() => ({}));
      if (res.status === 429) {
        setRemaining(0);
        track('Ask DocVex Limit');
        throw new Error(t.limit);
      }
      if (res.status === 503) throw new Error(t.busy);
      if (!res.ok) throw new Error(t.error);
      setRemaining(data.remaining);
      track('Ask DocVex Question');
      setTurns((list) => [...list, { q, a: data.refused ? t.refused : data.answer }]);
    } catch (err) {
      setError(err.message || t.error);
      // The question goes back in the box, to try again.
      if (!turns.length) setQuestion(q);
    } finally {
      setPending('');
      setBusy(false);
      input.current?.focus();
    }
  }

  const composer = (
    <form className="ask-composer" onSubmit={ask}>
      <textarea
        ref={input}
        rows={1}
        value={question}
        maxLength={500}
        placeholder={chat ? t.followUp : t.placeholder}
        aria-label={t.title}
        disabled={out}
        onChange={(e) => setQuestion(e.target.value)}
        onKeyDown={(e) => {
          if (e.key === 'Enter' && !e.shiftKey) ask(e);
        }}
      />
      <button
        type="submit"
        className="ask-send"
        aria-label={t.ask}
        disabled={busy || out || !question.trim()}
      >
        <svg viewBox="0 0 24 24" aria-hidden="true">
          <path d="M5 12h13M12 5l7 7-7 7" />
        </svg>
      </button>
    </form>
  );

  // Before the first question: just the field and its send button.
  if (!chat) {
    return (
      <div className="ask is-start">
        {composer}
        {error && (
          <p className="auth-error" role="alert">
            {error}
          </p>
        )}
        <p className="note ask-notice">{t.notice}</p>
      </div>
    );
  }

  return (
    <div className="ask is-chat">
      <div className="ask-head">
        <span className="ask-avatar" aria-hidden="true">
          D
        </span>
        <div>
          <b>{t.title}</b>
          <span className="note">{remaining !== null ? t.left(remaining) : t.asking}</span>
        </div>
      </div>

      <div className="ask-log" ref={log} aria-live="polite">
        {turns.map((turn, i) => (
          <div key={i} className="ask-pair">
            <p className="ask-bubble is-you">{turn.q}</p>
            <div className="ask-bubble is-bot">
              <Answer text={turn.a} animate={i === turns.length - 1} onType={toBottom} />
            </div>
          </div>
        ))}
        {pending && (
          <div className="ask-pair">
            <p className="ask-bubble is-you">{pending}</p>
            <div className="ask-bubble is-bot is-thinking" role="status">
              <span className="ask-dots" aria-hidden="true">
                <span />
                <span />
                <span />
              </span>
              {t.thinking}
            </div>
          </div>
        )}
        {error && (
          <p className="ask-error" role="alert">
            {error}
          </p>
        )}
      </div>

      {composer}
      <p className="note ask-notice">{t.notice}</p>
    </div>
  );
}
